# 공식 계산 함수
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def formula_min_curve_radius(V: int, e_max: int, f: float) -> tuple[float, str]:
    """
    최소 평면곡선반경 공식 계산.
    R = V² / (127 × (e/100 + f))   [도로설계기준 4.2.1]
    반환: (계산값, 공식문자열)
    """
    R = V ** 2 / (127 * (e_max / 100 + f))
    formula_str = (
        f"R = V² / (127×(e+f))"
        f" = {V}² / (127×({e_max/100:.2f}+{f})) = {R:.0f} m"
        f" → 기준 적용값 {MIN_CURVE_RADIUS.get(V, '?')} m"
    )
    return round(R, 0), formula_str


def formula_stopping_sight_distance(V: int) -> tuple[float, str]:
    """
    정지시거 공식 계산.
    D = V·t/3.6 + V²/(2·a·(1/3.6)⁻²)
      = V·t/3.6 + V²/(25.92·a)
    a = 4.5 m/s² (쾌적 제동가속도), t = 2.5 s (반응시간)
    [도로설계기준 6.2.1]
    """
    t = 2.5   # 반응시간 (s)
    a = 4.5   # 제동가속도 (m/s²)
    d_react = V * t / 3.6
    d_brake = V ** 2 / (25.92 * a)
    D = d_react + d_brake
    formula_str = (
        f"D = V·t/3.6 + V²/(25.92·a)"
        f" = {V}×{t}/3.6 + {V}²/(25.92×{a})"
        f" = {d_react:.1f} + {d_brake:.1f} = {D:.0f} m"
    )
    return round(D, 0), formula_str


def formula_transition_length(V: int) -> tuple[float, str]:
    """
    완화곡선 최소 길이 공식 계산.
    L ≥ V · t_min / 3.6  (t_min = 3.0 s)
    [도로설계기준 4.4.2]
    """
    t_min = 3.0
    L = V * t_min / 3.6
    formula_str = (
        f"L = V·t_min/3.6 = {V}×{t_min}/3.6 = {L:.1f} m"
        f" → 기준 적용값 {MIN_TRANSITION_LENGTH.get(V, '?')} m"
    )
    return round(L, 1), formula_str


def formula_superelevation(V: int, R: float, f: float) -> tuple[float, str]:
    """
    필요 편경사 공식 계산 (특정 반경에서).
    e = V² / (127·R) - f   [도로설계기준 4.3.1]
    """
    e = V ** 2 / (127 * R) - f
    e = max(0.0, e)
    formula_str = (
        f"e = V²/(127·R) - f"
        f" = {V}²/(127×{R:.0f}) - {f}"
        f" = {e*100:.1f}%  (최소 곡선반경 기준)"
    )
    return round(e * 100, 1), formula_str


def formula_widening(R: float, lane_count: int, l: float = 7.0) -> tuple[float, str]:
    """
    확폭량 계산 (기준표 적용, 참고 공식 병기).
    W_approx ≈ l² / (2·R)  [대형차 기준, 도로설계기준 4.5.2]
    실제 기준값은 도로설계기준 표 4-6에서 적용.
    """
    w_approx = l ** 2 / (2 * R)
    w_per_lane = _widening_per_lane(R)
    lanes_per_dir = max(1, lane_count // 2)
    w_total = w_per_lane * lanes_per_dir
    formula_str = (
        f"W_참고 ≈ l²/(2R) = {l}²/(2×{R:.0f}) = {w_approx:.3f} m/차로"
        f" → 기준표 적용 {w_per_lane} m/차로 × {lanes_per_dir}차로 = {w_total} m"
    )
    return w_total, formula_str


