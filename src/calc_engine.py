CROSSFALL_ROAD = 2.0       # 포장 노면
CROSSFALL_SHOULDER = 4.0  # 길어깨


# ─── 메인 산출 함수 ──────────────────────────────────────────────────────────

def calculate_all(road_grade: str, design_speed: int, terrain: str,
                  region: str, lane_count: int) -> dict:
    """
    입력 조건에 따라 전체 설계 파라미터를 산출합니다.

    Parameters
    ----------
    road_grade   : '고속도로' | '일반국도' | '지방도' | '시군도'
    design_speed : 40 | 60 | 80 | 100 | 120  (km/h)
    terrain      : '평지' | '구릉지' | '산지'
    region       : '지방지역' | '도시지역'
    lane_count   : int (차로 수)

    Returns
    -------
    dict  { category → [ {name, value, unit, condition, source}, ... ] }
    """
    results = {
        "inputs": {
            "road_grade":   road_grade,
            "design_speed": design_speed,
            "terrain":      terrain,
            "region":       region,
            "lane_count":   lane_count,
        },
        "params": []
    }

    def add(category, name, value, unit, condition="", source="도로설계기준"):
        results["params"].append({
            "category":  category,
            "name":      name,
            "value":     value if value is not None else "해당 없음",
            "unit":      unit,
            "condition": condition,
            "source":    source,
        })

    # ── 횡단 ────────────────────────────────────────────────────────────────
    lane_w = LANE_WIDTH.get(design_speed, 3.0)
    add("횡단", "차로폭", lane_w, "m",
        f"설계속도 {design_speed} km/h",
        "도로설계기준 제3장 3-1")

    r_shoulder = (RIGHT_SHOULDER.get(road_grade, {}) or {}).get(design_speed)
    add("횡단", "우측 길어깨폭", r_shoulder, "m",
        f"{road_grade} / 설계속도 {design_speed} km/h",
        "도로설계기준 제3장 3-3")

    l_shoulder = (LEFT_SHOULDER.get(road_grade, {}) or {}).get(design_speed)
    add("횡단", "좌측 길어깨폭", l_shoulder, "m",
        f"{road_grade} / 설계속도 {design_speed} km/h",
        "도로설계기준 제3장 3-4")

    median_map = MEDIAN_WIDTH.get(road_grade)
    if median_map and lane_count >= 4:
        median_w = median_map.get(design_speed)
    else:
        median_w = None
    add("횡단", "중앙분리대폭 (최소)", median_w, "m",
        "4차로 이상 / 분리도로" if median_w else "해당 없음",
        "도로설계기준 제3장 3-5")

    add("횡단", "노면 횡단경사", CROSSFALL_ROAD, "%",
        "직선 포장 구간", "도로설계기준 제3장")
    add("횡단", "길어깨 횡단경사", CROSSFALL_SHOULDER, "%",
        "비포장 길어깨 기준", "도로설계기준 제3장")

    # ── 선형 ────────────────────────────────────────────────────────────────
    add("선형", "최소 평면곡선반경", MIN_CURVE_RADIUS.get(design_speed), "m",
        f"최대편경사 {MAX_SUPERELEVATION[region]}% 기준",
        "도로설계기준 제4장 4-1")

    add("선형", "최대 편경사", MAX_SUPERELEVATION.get(region), "%",
        f"{region}", "도로설계기준 제4장")

    add("선형", "완화곡선 최소 길이", MIN_TRANSITION_LENGTH.get(design_speed), "m",
        f"설계속도 {design_speed} km/h (클로소이드)",
        "도로설계기준 제4장 4-3")

    # ── 종단 ────────────────────────────────────────────────────────────────
    max_g = (MAX_GRADE.get(road_grade, {}) or {}).get(terrain)
    add("종단", "최대 종단경사", max_g, "%",
        f"{road_grade} / {terrain}",
        "도로설계기준 제5장 5-1")

    add("종단", "최소 종단경사", MIN_GRADE, "%",
        "배수 처리 기준 (전 도로 공통)",
        "도로설계기준 제5장")

    add("종단", "볼록형 종단곡선 K값", CONVEX_K.get(design_speed), "",
        f"설계속도 {design_speed} km/h / 정지시거 기준",
        "도로설계기준 제5장 5-3")

    add("종단", "오목형 종단곡선 K값", CONCAVE_K.get(design_speed), "",
        f"설계속도 {design_speed} km/h / 전조등 조명 기준",
        "도로설계기준 제5장 5-4")

    # ── 시거 ────────────────────────────────────────────────────────────────
    add("시거", "정지시거", STOPPING_SIGHT_DISTANCE.get(design_speed), "m",
        f"설계속도 {design_speed} km/h",
        "도로설계기준 제6장 6-1")

    passing = PASSING_SIGHT_DISTANCE.get(design_speed)
    add("시거", "앞지르기시거", passing, "m",
        "2차로 도로 해당" if passing else "고속도로 해당 없음",
        "도로설계기준 제6장 6-2")

    return results
